"use client";

import React from "react";
import Link from "next/link";
import { usePathname } from "next/navigation";
import { useAuth } from "@/context/AuthContext";
import styles from "./Sidebar.module.css";

interface SidebarProps {
  isOpen: boolean;
  onClose: () => void;
}

export default function Sidebar({ isOpen, onClose }: SidebarProps) {
  const { user, logout } = useAuth();
  const pathname = usePathname();

  if (!user) return null;

  const role = user.role;

  // Define navigation links based on role
  const links = {
    OWNER: [
      { name: "Dashboard", href: "/owner/dashboard", icon: <DashboardIcon /> },
      { name: "Admissions", href: "/owner/students/admission", icon: <AddUserIcon /> },
      { name: "Students & Ledger", href: "/owner/students", icon: <UsersIcon /> },
      { name: "Fee Management", href: "/owner/fees", icon: <DollarIcon /> },
      { name: "Tests & Exams", href: "/owner/tests", icon: <AcademicIcon /> },
      { name: "Notice Board", href: "/owner/notices", icon: <NoticeIcon /> },
      { name: "Reports", href: "/owner/reports", icon: <ReportIcon /> },
      { name: "Audit Logs", href: "/owner/audit-logs", icon: <SettingsIcon /> },
    ],
    TEACHER: [
      { name: "Dashboard", href: "/teacher/dashboard", icon: <DashboardIcon /> },
      { name: "Schedule Planner", href: "/teacher/schedule", icon: <ScheduleIcon /> },
      { name: "Marks Entry", href: "/teacher/marks", icon: <AcademicIcon /> },
    ],
    PARENT: [
      { name: "Dashboard", href: "/parent/dashboard", icon: <DashboardIcon /> },
      { name: "Fee Ledger", href: "/parent/fees", icon: <DollarIcon /> },
      { name: "Academic Reports", href: "/parent/reports", icon: <AcademicIcon /> },
      { name: "Class Schedule", href: "/parent/schedule", icon: <ScheduleIcon /> },
    ],
  }[role] || [];

  return (
    <>
      {/* Mobile Overlay */}
      {isOpen && <div className={styles.overlay} onClick={onClose} />}

      <aside className={`${styles.sidebar} ${isOpen ? styles.open : ""}`}>
        <div className={styles.brand}>
          <div className={styles.logo}>
            <svg width="28" height="28" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" strokeLinejoin="round">
              <path d="M12 2L2 7l10 5 10-5-10-5zM2 17l10 5 10-5M2 12l10 5 10-5" />
            </svg>
          </div>
          <span className={styles.brandName}>Apex Academy</span>
        </div>

        <div className={styles.userInfo}>
          <div className={styles.avatar}>{user.name.charAt(0).toUpperCase()}</div>
          <div className={styles.userMeta}>
            <span className={styles.userName}>{user.name}</span>
            <span className={styles.userRole}>{role.toLowerCase()}</span>
            <button onClick={logout} className={styles.logoutBtnInline}>
              <span className={styles.logoutIcon}><LogoutIcon /></span>
              <span>Sign Out</span>
            </button>
          </div>
        </div>

        <nav className={styles.nav}>
          {links.map((link) => {
            const isActive = pathname === link.href || pathname.startsWith(link.href + "/");
            return (
              <Link
                key={link.name}
                href={link.href}
                className={`${styles.navLink} ${isActive ? styles.active : ""}`}
                onClick={onClose}
              >
                <span className={styles.icon}>{link.icon}</span>
                <span className={styles.linkLabel}>{link.name}</span>
              </Link>
            );
          })}
        </nav>

      </aside>
    </>
  );
}

